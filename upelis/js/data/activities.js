// The ten places as one season has them.
export function placesIn(seasonId) {
  const season = SEASONS.find((entry) => entry.id === seasonId);
  return PLACES.map(({ id, tone, view, seasons }) => {
    const { view: own, ...place } = seasons[seasonId];
    return { id, tone, season, ...place, view: { ...view, ...own } };
  });
}

